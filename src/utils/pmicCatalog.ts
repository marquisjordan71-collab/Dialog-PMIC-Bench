export type DeviceCategory =
  | 'pmic'
  | 'consumer-mobile'
  | 'consumer-gamepad'
  | 'consumer-gaming'
  | 'consumer-pd-dock'
  | 'consumer-audio-storage';

export interface RailDefinition {
  id: string;
  name: string;
  type: 'BUCK' | 'LDO';
  regAddr: string;
  enableReg: string;
  enableBit: number;
  minMv: number;
  maxMv: number;
  stepMv: number;
  defaultMv: number;
  maxCurrentMa: number;
  seqSlot: number;
  description: string;
}

export interface RegisterDefinition {
  addr: string;
  name: string;
  defaultVal: string;
  access: 'RO' | 'RW' | 'W1C';
  description: string;
}

export interface ManualDocument {
  id: string;
  partNumber: string;
  title: string;
  docType: 'Datasheet' | 'Register Map' | 'EVK Manual' | 'App Note' | 'Service Manual';
  revision: string;
  releaseDate: string;
  pages: number;
  fileSizeKb: number;
  officialUrl: string;
  summary: string;
  highlights: string[];
  sourceStatus?: 'verified' | 'local-archive';
}

export interface FirmwarePackage {
  id: string;
  partNumber: string;
  name: string;
  version: string;
  target: 'PMIC OTP / NVM' | 'USB-C OTG Bridge' | 'Device Controller / PD';
  releaseDate: string;
  sizeBytes: number;
  crc32: string;
  notes: string;
  patchRegisters: Array<{ addr: string; name: string; value: string; note: string }>;
  railOverrides?: Record<string, { mv?: number; enabled?: boolean }>;
}

export interface PmicProfile {
  partNumber: string;
  family: string;
  manufacturer: string;
  summary: string;
  packageType: string;
  i2cAddresses: string[];
  primaryI2cAddr: string;
  deviceIdReg: string;
  deviceIdValue: number;
  variantIdReg: string;
  variantIdValue: number;
  vinMinMv: number;
  vinMaxMv: number;
  nominalVinMv: number;
  firmwareVersion: string;
  otpRevision: string;
  rails: RailDefinition[];
  registers: RegisterDefinition[];
  pinoutHighlights: Array<{ pin: string; name: string; function: string }>;
  deviceCategory?: DeviceCategory;
  displayName?: string;
  controllerIc?: string;
  busProtocol?: string;
  usbVendorIds?: number[];
  searchAliases?: string[];
}

